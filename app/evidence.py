"""Builds the PayPal `provide-evidence` payload and a human-readable PDF evidence packet."""

from datetime import datetime, timezone

from fpdf import FPDF

from . import merchant_data

# Subset of the Disputes API tracking_info.carrier_name enum; anything else is sent as OTHER.
PAYPAL_CARRIERS = {"USPS", "UPS", "FEDEX", "DHL", "TNT", "ROYAL_MAIL", "PARCELFORCE", "CA_CANADA_POST", "CA_PUROLATOR"}
TRACKING_TYPES = {"PROOF_OF_FULFILLMENT", "PROOF_OF_DELIVERY_SIGNATURE", "PROOF_OF_RESHIPMENT"}


def _tracking_info(carrier: str, number: str) -> dict:
    code = (carrier or "").upper().replace(" ", "_")
    info = {"tracking_number": number}
    if code in PAYPAL_CARRIERS:
        info["carrier_name"] = code
    else:
        info.update(carrier_name="OTHER", carrier_name_other=carrier or "Unknown")
    return info


def build_evidences(analysis: dict, note: str, pdf_name: str) -> list[dict]:
    items = analysis.get("evidence") or [
        {"evidence_type": "OTHER", "title": "Seller statement", "details": note, "source": "Seller"}
    ]
    out = []
    for i, item in enumerate(items):
        ev = {"evidence_type": item["evidence_type"], "notes": (note if i == 0 else f"{item['title']}: {item['details']}")[:2000]}
        info = {}
        if item["evidence_type"] in TRACKING_TYPES and analysis.get("tracking_number"):
            info["tracking_info"] = [_tracking_info(analysis.get("tracking_carrier", ""), analysis["tracking_number"])]
        if item["evidence_type"] == "PROOF_OF_REFUND" and analysis.get("refund_id"):
            info["refund_ids"] = [analysis["refund_id"]]
        if info:
            ev["evidence_info"] = info
        if i == 0:
            ev["documents"] = [{"name": pdf_name}]
        out.append(ev)
    return out


def _t(text) -> str:
    """Core PDF fonts are Latin-1 only; normalise common Unicode punctuation."""
    s = str(text if text is not None else "")
    for a, b in {"—": "-", "–": "-", "‘": "'", "’": "'", "“": '"', "”": '"', "·": "-", "…": "...", "•": "-", "→": "->"}.items():
        s = s.replace(a, b)
    return s.encode("latin-1", "replace").decode("latin-1")


class _Packet(FPDF):
    def header(self):
        self.set_font("Helvetica", "B", 9)
        self.set_text_color(110, 110, 110)
        self.cell(0, 6, _t(self.title_text), new_x="LMARGIN", new_y="NEXT")
        self.set_text_color(0, 0, 0)

    def footer(self):
        self.set_y(-12)
        self.set_font("Helvetica", "", 8)
        self.set_text_color(130, 130, 130)
        self.cell(0, 6, f"Page {self.page_no()}  -  generated by Dispute Defender", align="C")


def build_pdf(dispute: dict, analysis: dict, note: str, merchant_name: str,
              order: dict | None = None, tracking: dict[str, dict] | None = None) -> bytes:
    """`order` / `tracking` let callers pass records fetched from PayPal or EasyPost; by default
    they're looked up in the store database."""
    tx = (dispute.get("disputed_transactions") or [{}])[0]
    if order is None:
        order = merchant_data.find_order(tx.get("seller_transaction_id", ""), tx.get("invoice_number", ""))
    tracking = tracking or {}
    pdf = _Packet(format="Letter")
    pdf.title_text = f"{merchant_name} - Evidence for PayPal dispute {dispute['dispute_id']}"
    pdf.set_auto_page_break(True, margin=15)
    pdf.add_page()

    def h(text):
        pdf.ln(3)
        pdf.set_font("Helvetica", "B", 12)
        pdf.cell(0, 7, _t(text), new_x="LMARGIN", new_y="NEXT")
        pdf.set_font("Helvetica", "", 10)

    def p(text):
        pdf.multi_cell(0, 5, _t(text), new_x="LMARGIN", new_y="NEXT")

    pdf.set_font("Helvetica", "B", 16)
    pdf.cell(0, 10, _t(f"Dispute {dispute['dispute_id']}"), new_x="LMARGIN", new_y="NEXT")
    pdf.set_font("Helvetica", "", 10)
    amount = dispute.get("dispute_amount", {})
    p(f"Reason: {dispute.get('reason')}   Stage: {dispute.get('dispute_life_cycle_stage')}   Amount: {amount.get('value')} {amount.get('currency_code')}")
    p(f"Transaction: {tx.get('seller_transaction_id')}   Invoice: {tx.get('invoice_number')}   Buyer: {(tx.get('buyer') or {}).get('name')}")
    p(f"Prepared: {datetime.now(timezone.utc).strftime('%Y-%m-%d %H:%M UTC')}")

    h("Seller statement")
    p(note)

    if analysis.get("key_facts"):
        h("Key facts")
        for f in analysis["key_facts"]:
            p(f"- {f['fact']}  [{f['source']}]")

    if analysis.get("evidence"):
        h("Evidence")
        for e in analysis["evidence"]:
            pdf.set_font("Helvetica", "B", 10)
            p(f"{e['title']} ({e['evidence_type']})")
            pdf.set_font("Helvetica", "", 10)
            p(f"{e['details']}  Source: {e['source']}")

    if order:
        h(f"Order record {order['order_id']}")
        a = order["shipping_address"]
        if order.get("source"):
            p(f"Source: {order['source']}")
        p(f"Placed {(order.get('placed') or '')[:16].replace('T', ' ')} UTC by {order['customer']['name']} <{order['customer']['email']}>")
        if order.get("seller_protection"):
            sp = order["seller_protection"]
            p(f"PayPal Seller Protection: {sp.get('status')} ({', '.join(sp.get('dispute_categories') or [])})")
        p("Items: " + "; ".join(f"{i['qty']} x {i['name']} ({i['sku']}) @ {i['price']}" for i in order["items"]))
        p(f"Total {order['total']} {order['currency']}. Ship to: {a.get('name')}, {a.get('line1')}, {a.get('city')}, {a.get('state')} {a.get('postal_code')}")
        for label, key in (("Outbound shipment", "fulfillment"), ("Customer return", "return")):
            shipment = order.get(key)
            if not shipment or not shipment.get("tracking_number"):
                continue
            track = tracking.get(shipment["tracking_number"]) or merchant_data.get_tracking(shipment["tracking_number"])
            h(f"{label}: {shipment['carrier']} {shipment['tracking_number']}")
            if track:
                if track.get("signed_by"):
                    p(f"Signed by: {track['signed_by']}")
                for ev in track.get("events", []):
                    p(f"{ev['time'][:16].replace('T', ' ')}  {ev['location']}  -  {ev['description']}")
        for r in order.get("refunds", []):
            p(f"Refund {r['refund_id']}: {r['amount']} {r['currency']} issued {(r.get('issued') or '')[:10]} ({r['status']})")
        tickets = merchant_data.search_support(order["customer"]["email"])
        if tickets:
            h("Customer correspondence")
            for t in tickets:
                p(f"{t['time'][:16].replace('T', ' ')}  {t['from'].upper()} ({t['channel']}): {t.get('subject', '')}")
                p(f"   \"{t['body']}\"")

    return bytes(pdf.output())
